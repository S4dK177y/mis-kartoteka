// Функция для поиска по МКБ-10
export const searchMKB10 = (query) => {
  if (!query) return [];
  const q = query.toLowerCase();
  return MKB10_CODES.filter(item => 
    item.code.toLowerCase().includes(q) || item.name.toLowerCase().includes(q)
  ).slice(0, 10); // Возвращаем топ 10 результатов
};
